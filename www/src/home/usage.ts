import { dedent } from "@src/util"
import { node } from "@src/index"
import { CodeBlock, Heading, List, ListItem, Paragraph } from "@www/component"
import { Monospace } from "@www/component/block"

const CREATE_DOCUMENT = dedent(`
    import { css, Document, node } from "@lonnycorp/htmlforge"

    const html = new Document({ displaySignature: false })
        .attribute("lang", "en")
        .attribute("data-theme", "dark")

    html.body
        .css(cls => css.css\`.\${cls} { margin: auto; }\`)
        .child(new node.Text("Hello world"))
`)

export class Usage extends node.Fragment {
    constructor() {
        super()
        this.child(new Heading(2, "Usage"))
            .child(new Heading(3, "HTML structure"))
            .child(new Paragraph(
                "An HTMLForge ",
                new Monospace("Document"),
                " instance is a tree of nodes. Nodes come in a few flavors:"
            ))
            .child(new List(
                new ListItem(
                    new Monospace("node.Element"),
                    ": represents tags (e.g., ",
                    new Monospace("<div>"),
                    ", ",
                    new Monospace("<span>"),
                    "), can hold attributes and CSS chunks, and can nest any other node as a child."
                ),
                new ListItem(new Monospace("node.Text"), ": holds plain text content that will be HTML-escaped."),
                new ListItem(new Monospace("node.Raw"), ": holds raw HTML without escaping."),
                new ListItem(
                    new Monospace("node.Fragment"),
                    ": groups a collection of child nodes without introducing a wrapping element."
                )
            ))
            .child(new Heading(3, "Creating an HTML document"))
            .child(new Paragraph(
                "Create a new HTML document using ",
                new Monospace("new Document()"),
                ", set attributes on the root ",
                new Monospace("<html>"),
                " element via ",
                new Monospace("html.attribute"),
                ", and work directly with ",
                new Monospace("html.head"),
                " and ",
                new Monospace("html.body"),
                " to populate content. The constructor accepts optional parameters:"
            ))
            .child(new List(new ListItem(
                new Monospace("displaySignature"),
                " (default ",
                new Monospace("true"),
                "): whether to include the ",
                new Monospace("<!-- Generated by HTMLForge -->"),
                " signature comment."
            )))
            .child(new CodeBlock(CREATE_DOCUMENT))
    }
}
